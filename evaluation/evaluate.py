"""Scoring of error classification (accuracy) and error detection (soft index matching, SIM).

Usage:
  python evaluate.py --task classification --data ../data/classification.json --pred predictions.csv
  python evaluate.py --task detection      --data ../data/detection.json      --pred predictions.csv

predictions.csv has the columns `id` (item id of the data file) and `prediction` (raw text generated by the model).
Every item of the data file must have a row; leave `prediction` empty when the model produced no output.
An empty or unparsable output is scored as incorrect.

Error correction is scored with GREEN (evaluation_green.py).
Requirements: pandas, numpy, rouge (pip install rouge).
"""
import argparse
import json
import re
import sys
import threading

import numpy as np
import pandas as pd

sys.setrecursionlimit(100000)   # the rouge package recurses once per word; long outputs exceed the default limit
ERROR_TYPES = ["omission", "insertion", "direction", "size", "typo", "unit"]


def is_missing(x):
    return x is None or (isinstance(x, float) and np.isnan(x)) or str(x).strip() == "" or str(x).strip().lower() == "nan"


# ---------------------------------------------------------------- error classification
def parse_binary(text):
    """First integer of the output; anything other than 0 or 1 is unparsable."""
    m = re.search(r"\d+", str(text))
    if m and int(m.group()) in (0, 1):
        return int(m.group())
    return None


def score_classification(items, pred):
    hit = []
    for x in items:
        p = None if is_missing(pred[x["id"]]) else parse_binary(pred[x["id"]])
        hit.append(int(p is not None and p == int(x["answer"])))
    return pd.DataFrame({"error_type": [x["error_type"] for x in items], "hit": hit})


# ---------------------------------------------------------------- error detection (SIM)
def split_sentences(text):
    return re.split(r"(?<=[.!?])\s+", text)


def clean_output(val):
    """Remove special tokens such as <s> and one leading / trailing quotation mark."""
    if is_missing(val):
        return None
    s = re.sub(r"<[^>]*>", "", str(val).strip()).strip()
    if s.startswith('"') or s.startswith("'"):
        s = s[1:].strip()
    if s.endswith('"') or s.endswith("'"):
        s = s[:-1].strip()
    return None if is_missing(s) else s


def best_match(text, sentences, rouge):
    """Index of the sentence with the highest ROUGE-L F1 score against the text."""
    best_score, best_idx = -1, -1
    for idx, sentence in enumerate(sentences):
        try:
            f = rouge.get_scores(text, sentence)[0]["rouge-l"]["f"]
        except Exception:      # the rouge package raises on sentences without word tokens
            continue
        if f > best_score:
            best_score, best_idx = f, idx
    return best_idx


def score_detection(items, pred):
    """SIM: the output is mapped to the most similar sentence of the report (or to "No errors detected.") and is
    correct when that sentence is the one the reference answer maps to. Items whose reference answer spans more
    than one sentence and items whose report has a single sentence are not scored."""
    from rouge import Rouge
    rouge = Rouge()
    rows = []
    for x in items:
        sentences = split_sentences(x["report"].strip())
        if len(split_sentences(x["answer"])) != 1 or len(sentences) <= 1:
            continue
        sentences = sentences + ["No errors detected."]
        ref_idx = best_match(x["answer"], sentences, rouge)
        out = clean_output(pred[x["id"]])
        hit = int(out is not None and best_match(out, sentences, rouge) == ref_idx)
        rows.append((x["error_type"], hit))
    return pd.DataFrame(rows, columns=["error_type", "hit"])


# ---------------------------------------------------------------- summary
def summarise(df):
    out = []
    for t in ERROR_TYPES:
        d = df[df.error_type == t]
        if len(d):
            out.append((t, len(d), d.hit.mean()))
    err = df[df.error_type != "none"]
    out.append(("error (micro)", len(err), err.hit.mean()))
    out.append(("error (macro)", len(err), np.mean([v for _, _, v in out[:-1]])))
    free = df[df.error_type == "none"]
    out.append(("error-free", len(free), free.hit.mean()))
    out.append(("all", len(df), df.hit.mean()))
    return pd.DataFrame(out, columns=["subset", "n_items", "score"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--task", required=True, choices=["classification", "detection"])
    ap.add_argument("--data", required=True)
    ap.add_argument("--pred", required=True)
    ap.add_argument("--out", default=None, help="optional CSV file for the summary table")
    args = ap.parse_args()

    items = json.load(open(args.data))
    assert all(x["task"] == args.task for x in items), "the data file does not belong to --task"
    p = pd.read_csv(args.pred, dtype={"id": str})
    assert {"id", "prediction"} <= set(p.columns), "predictions need the columns id and prediction"
    assert not p["id"].duplicated().any(), "duplicated ids in the predictions"
    pred = dict(zip(p["id"], p["prediction"]))
    missing = [x["id"] for x in items if x["id"] not in pred]
    if missing:
        raise SystemExit(f"{len(missing)} items have no row in the predictions, e.g. {missing[:3]}")

    df = score_classification(items, pred) if args.task == "classification" else score_detection(items, pred)
    res = summarise(df)
    print(res.to_string(index=False, float_format=lambda v: f"{v:.3f}"))
    if args.out:
        res.to_csv(args.out, index=False)


if __name__ == "__main__":
    threading.stack_size(512 * 1024 * 1024)   # room for the deep recursion of the rouge package
    worker = threading.Thread(target=main)
    worker.start()
    worker.join()
